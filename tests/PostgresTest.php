    public function testTheConsoleRunsStatementsIncludingDollarQuotedBodies(): void
    {
        $client = $this->pgClient(self::ITEMS);
        $console = new Console($client, 2, 1024);

        $result = $console->run(<<<'SQL'
            CREATE FUNCTION shout(t text) RETURNS text LANGUAGE plpgsql AS $body$
            BEGIN
                RAISE NOTICE 'shouting; loudly';
                RETURN upper(t);
            END
            $body$;
            INSERT INTO items (name) VALUES ('a'), ('b'), ('c');
            SELECT shout(name) AS loud FROM items ORDER BY id;
            SQL, null, false, false);

        self::assertSame(3, count($result['results']));
        self::assertSame('INSERT 0 3', $result['results'][1]['sets'][0]['info']);
        self::assertSame(3, $result['results'][1]['sets'][0]['affected']);

        $select = $result['results'][2]['sets'][0];
        self::assertSame([['A'], ['B']], $select['rows'], 'Only the row limit is shown.');
        self::assertSame(true, $select['truncated']);
        self::assertSame('loud', $select['columns'][0]['name']);
        self::assertSame('shouting; loudly', $result['results'][2]['warnings'][0]['message']);
        self::assertSame($this->pgTarget()['database'], $result['database']);
    }

    public function testTheConsoleStopsAtTheFirstError(): void
    {
        $client = $this->pgClient(self::ITEMS);

        $result = (new Console($client, 100, 1024))->run("SELECT 1; SELECT * FROM missing; SELECT 2", null, false, false);

        self::assertSame(2, count($result['results']));
        self::assertTrue(str_contains($result['results'][1]['error'], 'relation "missing" does not exist'), $result['results'][1]['error']);
    }

    public function testTheConsoleKeepsATransactionTheUserOpened(): void
    {
        $client = $this->pgClient(self::ITEMS);
        $console = new Console($client, 100, 1024);

        $console->run("BEGIN; INSERT INTO items (name) VALUES ('kept'); SELECT count(*) FROM items", null, false, false);

        self::assertSame(PGSQL_TRANSACTION_INTRANS, pg_transaction_status($client->connection()), 'Reading a SELECT through a cursor must not commit the transaction around it.');

        $client->statement('ROLLBACK');
        self::assertSame('0', $client->value('SELECT count(*) FROM items'));
    }

    public function testDestructiveStatementsWaitForConfirmation(): void
    {
        $client = $this->pgClient(self::ITEMS);

        $result = (new Console($client, 100, 1024))->run('DELETE FROM items', null, false, false);

        self::assertTrue(isset($result['confirm']));
    }

    public function testAReadOnlySessionCannotWriteEvenThroughAFunction(): void
    {
        $this->pgClient(self::ITEMS, "CREATE FUNCTION sneak() RETURNS void LANGUAGE sql AS \$\$ INSERT INTO items (name) VALUES ('x') \$\$");
        $target = $this->pgTarget();
        $readOnly = (new Connection($this->pgConfig()))->open(['user' => $target['user'], 'password' => $target['password'], 'readonly' => true]);

        $result = (new Console($readOnly, 100, 1024))->run('SELECT sneak()', null, true, false);
        $readOnly->close();

        self::assertTrue(str_contains($result['results'][0]['error'] ?? '', 'read-only transaction'), json_encode($result));
    }

    public function testSearchCountsMatchesInEveryTable(): void
    {
        $client = $this->pgClient(self::ITEMS, self::ORDERS, "INSERT INTO items (name) VALUES ('Lamp'), ('lampshade'), ('desk')", "INSERT INTO orders (item_id, code) VALUES (1, 'LAMP-1')");
        $catalog = $this->catalog($client);
        $database = $this->pgTarget()['database'];

        $result = (new Search($client, $catalog, new Rows($client, $catalog, 1024, 1024, 100000)))->run($database, 'lamp', [], 10);

        self::assertSame([['table' => 'items', 'matches' => 2], ['table' => 'orders', 'matches' => 1]], $result['results']);
    }

    public function testATableAndAQueryAreExportedAsCsv(): void
    {
        $client = $this->pgClient(self::ITEMS, "INSERT INTO items (name, note) SELECT 'item ' || n, CASE WHEN n = 2 THEN 'has, comma' END FROM generate_series(1, 2500) AS n");
        $csv = '';
        $export = new Export($client, $this->catalog($client), static function (string $bytes) use (&$csv): void {
            $csv .= $bytes;
        });

        $export->csvTable($this->pgTarget()['database'], 'items');
        $lines = explode("\r\n", trim($csv));

        self::assertSame('id,name,note,price,tags,payload,name_length', $lines[0]);
        self::assertSame(2501, count($lines), 'Every row is streamed, past the cursor\'s batch size.');
        self::assertSame('2,item 2,"has, comma",0.00,,,6', $lines[2]);

        $csv = '';
        $export->csvQuery($this->pgTarget()['database'], 'SELECT name FROM items WHERE id <= 2 ORDER BY id');
        self::assertSame("name\r\nitem 1\r\nitem 2\r\n", $csv);

        self::assertThrows(UserError::class, fn () => $export->csvQuery(null, 'DELETE FROM items'), 'reads');
    }

    public function testMovingToAnotherDatabaseReconnects(): void
    {
        $client = $this->pgClient(self::ITEMS);
        $target = $this->pgTarget();

        $client->useDatabase($target['other']);
        self::assertSame($target['other'], $client->value('SELECT current_database()'));

        self::assertSame('"public"."items"', $client->qualified($target['database'], 'items'));
        self::assertSame($target['database'], $client->value('SELECT current_database()'));
    }

    public function testProcessesListOnlyTheRolesOtherSessions(): void
    {
        $client = $this->pgClient();
        $target = $this->pgTarget();
        $other = (new Connection($this->pgConfig()))->open(['user' => $target['user'], 'password' => $target['password']]);

        try {
            $processes = (new Processes($client, $target['user']))->all();
            $own = (int) $client->value('SELECT pg_backend_pid()');

            self::assertTrue($processes !== []);
            self::assertTrue(! in_array($own, array_column($processes, 'id'), true), 'The listing connection is left out.');
            self::assertSame([], (new Processes($client, 'somebody_else'))->all());
        } finally {
            $other->close();
        }
    }

