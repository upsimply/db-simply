    public function testValuesAreQuotedSafely(): void
    {
        $client = $this->pgClient();

        foreach (["it's", 'back\\slash', "multi\nline", 'emoji 🐘', "\$\$dollar\$\$"] as $value) {
            self::assertSame($value, $client->value('SELECT '.$client->quote($value)));
        }

        self::assertSame('"we""ird"', $client->identifier('we"ird'));
        self::assertTrue($client instanceof PgsqlClient);
    }
