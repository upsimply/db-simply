    }

    public function testRowsArePagedSortedSearchedAndFiltered(): void
    {
        $client = $this->pgClient(self::ITEMS, "INSERT INTO items (name, note, price) VALUES ('Apple', repeat('x', 3000), 2.50), ('banana', NULL, 1), ('Cherry', 'red', 12)");
        $rows = new Rows($client, $this->catalog($client), 1024, 1048576, 100000);
        $database = $this->pgTarget()['database'];

        $page = $rows->page($database, 'items', ['sort' => 'name', 'direction' => 'desc', 'limit' => 2]);
        self::assertSame(['Cherry', 'banana'], array_column($page['rows'], 1));
        self::assertSame(true, $page['hasMore']);
        self::assertSame(['id'], $page['key']);
        self::assertSame(3, $page['total']);

        $apple = $rows->page($database, 'items', ['search' => 'APPLE']);
        self::assertSame(1, count($apple['rows']), 'Search ignores case, as on MariaDB and MySQL.');
        self::assertSame(['$t' => str_repeat('x', 1024), 'len' => 3000], $apple['rows'][0][2], 'A long value is read as its start and its length.');

        $cheap = $rows->page($database, 'items', ['filters' => [['column' => 'price', 'operator' => '<', 'value' => '5'], ['column' => 'id', 'operator' => 'contains', 'value' => '2']]]);
        self::assertSame(['banana'], array_column($cheap['rows'], 1), 'A pattern matches a number by its text.');

        $empty = $rows->page($database, 'items', ['filters' => [['column' => 'note', 'operator' => 'is empty']]]);
        self::assertSame(['banana'], array_column($empty['rows'], 1));

        $value = $rows->value($database, 'items', 'note', ['id' => 1]);
        self::assertSame(str_repeat('x', 3000), $value['value']);
    }

    public function testRowsAreInsertedUpdatedAndDeleted(): void
    {
        $client = $this->pgClient(self::ITEMS);
        $editor = new Editor($client, $this->catalog($client), 1048576);
        $database = $this->pgTarget()['database'];

        $fields = array_column($editor->fields($database, 'items'), null, 'name');
        self::assertSame(true, $fields['id']['autoIncrement']);
        self::assertSame(true, $fields['name_length']['generated']);
        self::assertSame(true, $fields['note']['long']);
        self::assertSame(true, $fields['price']['numeric']);

        self::assertSame(['insertId' => '1'], $editor->insert($database, 'items', ['name' => 'Apple', 'tags' => '{"a": 1}', 'payload' => '\x0102']));
        self::assertSame(['insertId' => '2'], $editor->insert($database, 'items', ['name' => "O'Brien\\"]));

        $row = $editor->row($database, 'items', ['id' => 2]);
        self::assertSame("O'Brien\\", $row['values']['name']);
        self::assertSame('8', $row['values']['name_length']);
        self::assertSame('\x0102', $editor->row($database, 'items', ['id' => 1])['values']['payload'], 'bytea reads and writes in its hex form.');

        self::assertSame(['changed' => 1], $editor->update($database, 'items', ['id' => 2], ['note' => 'renamed', 'price' => '3.10']));
        self::assertSame('3.10', $client->value('SELECT price FROM items WHERE id = 2'));

        self::assertThrows(UserError::class, fn () => $editor->update($database, 'items', ['id' => 2], ['name_length' => '1']), 'generated');

        self::assertSame(['deleted' => 2], $editor->delete($database, 'items', [['id' => 1], ['id' => 2]]));
        self::assertSame('0', $client->value('SELECT count(*) FROM items'));
    }

