    private const string ITEMS = "CREATE TABLE items (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(50) NOT NULL,
        note text NULL,
        price numeric(8, 2) NOT NULL DEFAULT 0,
        tags jsonb NULL,
        payload bytea NULL,
        name_length integer GENERATED ALWAYS AS (char_length(name)) STORED
    )";

    private const string ORDERS = 'CREATE TABLE orders (
        id bigserial PRIMARY KEY,
        item_id integer NOT NULL REFERENCES items (id) ON DELETE CASCADE,
        code text NOT NULL UNIQUE
    )';

    public function testTheCatalogDescribesTablesInTheShapesMysqlFills(): void
    {
        $client = $this->pgClient(self::ITEMS, self::ORDERS, 'CREATE VIEW cheap AS SELECT id, name FROM items WHERE price < 10', "COMMENT ON TABLE items IS 'Things we sell'");
        $catalog = $this->catalog($client);
        $database = $this->pgTarget()['database'];

        self::assertTrue(in_array($database, $catalog->databaseNames(), true));
        self::assertTrue(! in_array('strangers', $catalog->databaseNames(), true), 'A database the role cannot connect to is not listed.');
        self::assertTrue(! in_array('template1', $catalog->databaseNames(), true));

        $tables = array_column($catalog->tables($database), null, 'name');
        self::assertSame(['cheap', 'items', 'orders'], array_keys($tables));
        self::assertSame(true, $tables['cheap']['view']);
        self::assertSame('Things we sell', $tables['items']['comment']);

        $columns = array_column($catalog->columns($database, 'items'), null, 'name');
        self::assertSame('integer', $columns['id']['dataType']);
        self::assertSame('auto_increment', $columns['id']['extra']);
        self::assertSame('PRI', $columns['id']['key']);
        self::assertSame('character varying(50)', $columns['name']['type']);
        self::assertSame('character varying', $columns['name']['dataType']);
        self::assertSame(200, $columns['name']['octetLength']);
        self::assertSame('jsonb', $columns['tags']['dataType']);
        self::assertSame('STORED GENERATED', $columns['name_length']['extra']);
        self::assertSame(null, $columns['name_length']['default']);

        self::assertSame(['id'], $catalog::rowKey($catalog->columns($database, 'orders'), $catalog->indexes($database, 'orders')));

        $keys = $catalog->foreignKeys($database, 'orders');
        self::assertSame(1, count($keys));
        self::assertSame(['item_id'], $keys[0]['columns']);
        self::assertSame('items', $keys[0]['referencedTable']);
        self::assertSame(['id'], $keys[0]['referencedColumns']);
        self::assertSame('CASCADE', $keys[0]['onDelete']);

        $create = $catalog->createStatement($database, 'items');
        self::assertTrue(str_contains($create, 'CREATE TABLE "public"."items"'), $create);
        self::assertTrue(str_contains($create, '"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL'), $create);
        self::assertTrue(str_contains($create, 'GENERATED ALWAYS AS (char_length((name)::text)) STORED'), $create);
        self::assertTrue(str_contains($create, 'PRIMARY KEY (id)'), $create);
        self::assertTrue(str_contains($catalog->createStatement($database, 'cheap'), 'CREATE VIEW "public"."cheap" AS'));
    }

    public function testATableNamedByTheBrowserMustExistInTheCurrentSchema(): void
    {
        $client = $this->pgClient(self::ITEMS);
        $catalog = $this->catalog($client);

        self::assertThrows(UserError::class, fn () => $catalog->table($this->pgTarget()['database'], 'pg_class'), 'does not exist');
